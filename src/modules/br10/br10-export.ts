// CommonJS modules; the project tsconfig has no esModuleInterop, so no default imports.
import * as ExcelJS from 'exceljs';
import PDFDocument = require('pdfkit');

export interface MaskRule { column_name: string; applies_to: 'EXPORT' | 'ALWAYS' | 'PII'; mask_rule: 'REDACT' | 'PARTIAL' }

/**
 * Apply masks for this context (T20):
 *   ALWAYS -> masked on screen and in exports
 *   EXPORT -> masked in exports only
 *   PII    -> masked on screen and in exports UNLESS the viewer holds an ACTIVE
 *             PII_CUSTOMER grant for this action on every company in scope (migration 021)
 */
export function applyMasks(rows: Record<string, unknown>[], masks: MaskRule[], ctx: 'VIEW' | 'EXPORT', piiUnmasked = false) {
  const active = masks.filter((m) =>
    m.applies_to === 'ALWAYS' || (m.applies_to === 'EXPORT' && ctx === 'EXPORT') || (m.applies_to === 'PII' && !piiUnmasked));
  if (active.length === 0) return rows;
  return rows.map((r) => {
    const o = { ...r };
    for (const m of active) {
      if (!(m.column_name in o) || o[m.column_name] === null || o[m.column_name] === undefined) continue;
      if (m.mask_rule === 'REDACT') o[m.column_name] = '[REDACTED]';
      else {
        const v = typeof o[m.column_name] === 'string' ? (o[m.column_name] as string) : JSON.stringify(o[m.column_name]);
        o[m.column_name] = v.length <= 2 ? '**' : `${v.slice(0, 2)}${'*'.repeat(Math.min(8, v.length - 2))}`;
      }
    }
    return o;
  });
}

const cell = (v: unknown): string => {
  if (v === null || v === undefined) return '';
  if (v instanceof Date) return v.toISOString();
  if (typeof v === 'object') return JSON.stringify(v);
  return String(v);
};

function columns(rows: Record<string, unknown>[]): string[] {
  const set = new Set<string>();
  rows.forEach((r) => Object.keys(r).forEach((k) => set.add(k)));
  return [...set];
}

export interface ExportMeta { title: string; reportCode: string; generatedBy: string; generatedAt: string; companies: string[]; period: string; kpiStatus: string }

export function toCsv(rows: Record<string, unknown>[]): Buffer {
  const cols = columns(rows);
  const esc = (s: string) => (/[",\r\n]/.test(s) || /^[=+\-@]/.test(s) ? `"${(/^[=+\-@]/.test(s) ? "'" : '') + s.replace(/"/g, '""')}"` : s);
  const lines = [cols.join(','), ...rows.map((r) => cols.map((c) => esc(cell(r[c]))).join(','))];
  return Buffer.from('﻿' + lines.join('\r\n'), 'utf8');
}

export async function toXlsx(rows: Record<string, unknown>[], meta: ExportMeta): Promise<Buffer> {
  const wb = new ExcelJS.Workbook();
  wb.creator = 'Brightech JMS BR-10';
  const ws = wb.addWorksheet(meta.reportCode.slice(0, 31));
  const cols = columns(rows);
  ws.columns = cols.map((c) => ({ header: c, key: c, width: Math.min(40, Math.max(12, c.length + 2)) }));
  rows.forEach((r) => ws.addRow(Object.fromEntries(cols.map((c) => [c, cell(r[c])]))));
  ws.getRow(1).font = { bold: true };
  const info = wb.addWorksheet('About');
  [['Report', meta.title], ['Code', meta.reportCode], ['KPI status', meta.kpiStatus], ['Companies', meta.companies.join(', ')],
    ['Period', meta.period], ['Generated by', meta.generatedBy], ['Generated at', meta.generatedAt],
    ['Note', 'Read-only extract. Masking policy applied (BR-10 10C-08).']].forEach((x) => info.addRow(x));
  return Buffer.from(await wb.xlsx.writeBuffer());
}

export function toPdf(rows: Record<string, unknown>[], meta: ExportMeta): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: 'A4', layout: 'landscape', margin: 30 });
    const chunks: Buffer[] = [];
    doc.on('data', (c: Buffer) => chunks.push(c));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);
    doc.fontSize(14).text(meta.title);
    doc.fontSize(8).fillColor('#555')
      .text(`${meta.reportCode} | KPI ${meta.kpiStatus} | companies ${meta.companies.join(', ')} | period ${meta.period}`)
      .text(`Generated by ${meta.generatedBy} at ${meta.generatedAt}. Read-only extract; masking applied.`)
      .moveDown().fillColor('#000');
    const cols = columns(rows);
    if (rows.length === 0) doc.fontSize(9).text('No rows in scope.');
    rows.forEach((r, i) => {
      doc.fontSize(7).text(`#${i + 1}  ` + cols.map((c) => `${c}: ${cell(r[c])}`).join('  |  '));
    });
    doc.end();
  });
}
